/**
 * The SD card layout the Play feature manages.
 *
 * One constant table; every other module derives its paths from it. The
 * tree mirrors how the official RetroArch Switch release installs (extract
 * at the SD root: `switch/retroarch_switch.nro`, `retroarch/`,
 * `retroarch.jpg`), plus a RomMmate-owned area for the content we download:
 *
 *   sdmc:/switch/rommmate/            app data (manifest, session marker, log)
 *   sdmc:/switch/rommmate/roms/<platform>/   downloaded roms
 *   sdmc:/switch/rommmate/saves|states/      RetroArch writes here; we sync from here
 *   sdmc:/switch/rommmate/covers/           cached cover art
 *   sdmc:/switch/retroarch_switch.nro       RetroArch loader (from RomM)
 *   sdmc:/retroarch.jpg               the launcher icon (from RomM)
 *   sdmc:/retroarch/retroarch.cfg     generated by us (pointing saves/states
 *   sdmc:/retroarch/cores/*.nro       at our own directories)
 *   sdmc:/retroarch/cores/system/     BIOS (from RomM firmware)
 *
 * We own the cfg (or patch it), so the save-file locations are
 * deterministic and the sync layer can find them by basename.
 */

export const PATHS = {
	/** App data (manifest, pending-session marker). */
	appDir: 'sdmc:/switch/rommmate',
	manifest: 'sdmc:/switch/rommmate/manifest.json',
	pendingSession: 'sdmc:/switch/rommmate/pending-session.json',

	/** The RetroArch loader + its icon (from the official release, via RomM). */
	loader: 'sdmc:/switch/retroarch_switch.nro',
	icon: 'sdmc:/retroarch.jpg',

	/** RetroArch's own tree. */
	raDir: 'sdmc:/retroarch',
	raCfg: 'sdmc:/retroarch/retroarch.cfg',
	coresDir: 'sdmc:/retroarch/cores',
	/** Where cores look for BIOS (RetroArch's `system_directory`). */
	biosDir: 'sdmc:/retroarch/cores/system',

	/** Our content area. */
	romsDir: 'sdmc:/switch/rommmate/roms',
	savesDir: 'sdmc:/switch/rommmate/saves',
	statesDir: 'sdmc:/switch/rommmate/states',
} as const;

/** The per-rom save directory: `sdmc:/switch/rommmate/saves/<romId>/`. */
export function saveDirFor(romId: number): string {
	return `${PATHS.savesDir}/${romId}`;
}

/** The per-rom states directory: `sdmc:/switch/rommmate/states/<romId>/`. */
export function stateDirFor(romId: number): string {
	return `${PATHS.statesDir}/${romId}`;
}

/**
 * The platform slug for a RomM platform name: lowercased, every
 * non-alphanumeric character stripped. "Nintendo Entertainment System" →
 * `nintendoentertainsystem`, "PS1" → `ps1`. Slugs are the stable key for
 * the roms subdirectory and for the core map.
 */
export function platformSlug(name: string): string {
	return name.toLowerCase().replace(/[^a-z0-9]/g, '');
}

/**
 * The (sanitised) file name of a rom as installed on the SD: the server's
 * `fs_name` with the characters the FAT32 SD filesystem rejects, replaced.
 */
export function romFileName(fsName: string): string {
	return fsName
		.replace(/[/\\:*?"<>|]/g, ' ')
		.replace(/\s+/g, ' ')
		.trim();
}

/** The install directory of a rom, per platform. */
export function romDir(platform: string): string {
	return `${PATHS.romsDir}/${platformSlug(platform) || 'other'}`;
}

/**
 * The full install path of one rom file:
 * `sdmc:/switch/rommmate/roms/<platform>/<fs_name>`.
 */
export function romPath(platform: string, fsName: string): string {
	return `${romDir(platform)}/${romFileName(fsName)}`;
}

/**
 * The part of a file name RetroArch uses to name its save files: the base
 * name without extension (a game `Foo (USA).gba` writes `Foo (USA).srm`).
 * Expects a bare file name, not a path.
 */
export function baseName(fileName: string): string {
	const i = fileName.lastIndexOf('.');
	return i > 0 ? fileName.slice(0, i) : fileName;
}

/**
 * The save-naming base of any path: the last path segment, extension
 * stripped. The install tree stores full paths (`sdmc:/…/Foo (USA).gba`),
 * so `baseName` on one would keep the directories — this does not.
 */
export function baseNameOf(pathOrName: string): string {
	const slash = Math.max(pathOrName.lastIndexOf('/'), pathOrName.lastIndexOf('\\'));
	return baseName(slash >= 0 ? pathOrName.slice(slash + 1) : pathOrName);
}
